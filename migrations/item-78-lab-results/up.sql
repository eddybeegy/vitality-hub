-- Item 78: blood test results. Idempotent; server.ts creates this table from its
-- schema map on boot, so on a live database this is a no-op.
--
-- Postgres syntax. SQLite: use INTEGER PRIMARY KEY AUTOINCREMENT for id and drop
-- the GENERATED clause; MySQL: AUTO_INCREMENT. taken_on is VARCHAR, not TEXT, so a
-- UNIQUE key can cover it on MySQL (same reason as day_tags).

CREATE TABLE IF NOT EXISTS lab_results (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER,
  taken_on    VARCHAR(10),
  analyte     VARCHAR(40),
  value       REAL,
  unit        VARCHAR(16),
  ref_low     REAL,
  ref_high    REAL,
  lab         VARCHAR(60),
  notes       TEXT,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (user_id, taken_on, analyte)
);

-- Reads are "everything for this user, oldest first" (trends need the whole series),
-- so the UNIQUE key above already covers the access path. No extra index.
